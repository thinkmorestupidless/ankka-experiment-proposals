// A finding or a claim: its statement, each span beside the passage it resolves to, every check of
// its latest verification with the verifier's rationale, its status and its attempts; the review form.
import type { EvidenceRecord, RecordView } from "../backend/types.ts";
import { tag } from "../backend/types.ts";
import { Card } from "./Card.tsx";
import { Checks } from "./Check.tsx";
import { Facts, Field, List } from "./Field.tsx";
import type { CardProps } from "./GenericCard.tsx";
import { Passage } from "./Passage.tsx";
import { RecordReview } from "../decisions/RecordReview.tsx";

export function statementOf(r: EvidenceRecord): string {
  const c = r.content;
  if (!c) return "";
  if (tag(c.type) === "OfClaim" && "claim" in c) return c.claim.proposition;
  if ("finding" in c) {
    const f = c.finding;
    return `${f.observedEndpoint}: ${f.reportedOutcome}`;
  }
  return "";
}

export function RecordCard({ kind, id, record, onOpen, onShowStage, onChanged }: CardProps) {
  const view = record as RecordView;
  const r = view.record ?? ({ id } as EvidenceRecord);
  const attempts = r.attempts ?? [];
  const latest = [...attempts].reverse().find((a) => a.verification);
  const v = latest?.verification;
  const finding = r.content && "finding" in r.content ? r.content.finding : undefined;
  const status = tag(r.status);
  return (
    <Card kind={kind} id={id} version={r.version} record={record} onOpen={onOpen} onShowStage={onShowStage}>
      <p className="edp-statement">{statementOf(r)}</p>
      <Facts>
        <Field label="Status">{status}</Field>
        <Field label="Source">{r.sourceRef ? `${r.sourceRef.id} version ${r.sourceRef.version}` : null}</Field>
        <Field label="Generated by">{r.generatedBy}</Field>
        {finding ? (
          <>
            <Field label="Species">{finding.species}</Field>
            <Field label="Cell type">{finding.cellType}</Field>
            <Field label="Experimental model">{finding.experimentalModel}</Field>
            <Field label="Conditions">
              <List items={finding.conditions} />
            </Field>
            <Field label="Limitations">
              <List items={finding.limitations} />
            </Field>
          </>
        ) : null}
        {r.defect ? <Field label="Defect">{`${tag(r.defect.kind)} (${tag(r.defect.severity)}): ${r.defect.detail}`}</Field> : null}
      </Facts>
      <div className="edp-beside">
        <h4>Its spans, beside the source</h4>
        {(view.spans ?? []).length === 0 ? <p className="ui-hint">none</p> : null}
        {(view.spans ?? []).map((s, n) => (
          <Passage key={n} view={s} />
        ))}
      </div>
      <div className="edp-verification">
        <h4>Verification</h4>
        {v ? (
          <>
            <Facts>
              <Field label="Label">{tag(v.label)}</Field>
              <Field label="Attempt">{String(v.attempt)}</Field>
              <Field label="Verified at">{v.verifiedAt}</Field>
              <Field label="Rationale">
                <span className="edp-rationale">{v.rationale}</span>
              </Field>
            </Facts>
            <Checks checks={v.checks} />
          </>
        ) : (
          <p className="ui-hint">Not verified yet.</p>
        )}
      </div>
      <div className="edp-attempts">
        <h4>Attempts</h4>
        <ol className="edp-list">
          {attempts.map((a) => (
            <li key={a.n} data-attempt={a.n}>
              attempt {a.n} by {a.generatedBy} at {a.at}: {a.outcome ? tag(a.outcome) : "pending"}
              {a.defect ? `, ${tag(a.defect.kind)}: ${a.defect.detail}` : ""}
              {a.triggeredBy ? ` (after ${tag(a.triggeredBy.kind)})` : ""}
            </li>
          ))}
        </ol>
      </div>
      {(r.reviews ?? []).length > 0 ? (
        <div className="edp-history">
          <h4>Reviews</h4>
          <ul className="edp-list">
            {(r.reviews ?? []).map((x, n) => (
              <li key={n}>
                {tag(x.action)} by {x.reviewer} at <time dateTime={x.at}>{x.at}</time>: {x.rationale}
              </li>
            ))}
          </ul>
        </div>
      ) : null}
      {kind === "finding" || kind === "claim" ? (
        <RecordReview kind={kind} recordId={id} open={status === "requires_review" || status === "proposed"} onDone={onChanged} />
      ) : null}
    </Card>
  );
}
